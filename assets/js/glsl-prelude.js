/* ============================================================================
   Shared GLSL prelude — injected ahead of every single-pass fragment shader.
   Target: WebGL2 / GLSL ES 3.00.  Kept free of overloads, `break` and structs
   so every world stays portable (and machine-checkable).
   ========================================================================== */
(function (w) {
  'use strict';

  var VERT = [
    '#version 300 es',
    'in vec2 aPos;',
    'out vec2 vUv;',
    'void main(){',
    '  vUv = aPos * 0.5 + 0.5;',
    '  gl_Position = vec4(aPos, 0.0, 1.0);',
    '}'
  ].join('\n');

  var PRELUDE = [
    '#version 300 es',
    'precision highp float;',
    'precision highp int;',
    'precision highp sampler2D;',
    '',
    'in  vec2 vUv;',
    'out vec4 fragColor;',
    '',
    'uniform vec2  uRes;      // pixel size of the surface',
    'uniform float uTime;     // seconds since this world was entered',
    'uniform float uDt;       // clamped delta seconds',
    'uniform float uFade;     // 0 -> 1 intro reveal',
    'uniform vec2  uMouse;    // -1..1, y up, smoothed',
    'uniform float uEnergy;   // slow 0..1 breath',
    'uniform float uRand;     // per-visit seed',
    '',
    'uniform float uPulse,uIntensity,uDetail,uDensity,uNovelty,uColorRange,uColorSafe,uBass,uMid,uTreble,uOnset,uStereo;',
    '#define PI  3.14159265359',
    '#define TAU 6.28318530718',
    '#define GOLD 0.61803398875',
    '',
    'mat2 rot2(float a){ float c = cos(a), s = sin(a); return mat2(c, -s, s, c); }',
    'mat3 rotX(float a){ float c = cos(a), s = sin(a); return mat3(1.0,0.0,0.0, 0.0,c,-s, 0.0,s,c); }',
    'mat3 rotY(float a){ float c = cos(a), s = sin(a); return mat3(c,0.0,s, 0.0,1.0,0.0, -s,0.0,c); }',
    'mat3 rotZ(float a){ float c = cos(a), s = sin(a); return mat3(c,-s,0.0, s,c,0.0, 0.0,0.0,1.0); }',
    '',
    'float hash11(float p){ p = fract(p * 0.1031); p *= p + 33.33; p *= p + p; return fract(p); }',
    'float hash12(vec2 p){',
    '  vec3 q = fract(vec3(p.xyx) * 0.1031);',
    '  q += dot(q, q.yzx + 33.33);',
    '  return fract((q.x + q.y) * q.z);',
    '}',
    'vec2 hash22(vec2 p){',
    '  vec3 q = fract(vec3(p.xyx) * vec3(0.1031, 0.1030, 0.0973));',
    '  q += dot(q, q.yzx + 33.33);',
    '  return fract((q.xx + q.yz) * q.zy);',
    '}',
    'vec3 hash33(vec3 p){',
    '  p = fract(p * vec3(0.1031, 0.1030, 0.0973));',
    '  p += dot(p, p.yxz + 33.33);',
    '  return fract((p.xxy + p.yxx) * p.zyx);',
    '}',
    'float hash13(vec3 p){',
    '  p = fract(p * 0.1031); p += dot(p, p.zyx + 31.32); return fract((p.x + p.y) * p.z);',
    '}',
    '',
    '// ---- value noise (2D / 3D) -------------------------------------------',
    'float vnoise2(vec2 p){',
    '  vec2 i = floor(p), f = fract(p);',
    '  vec2 u = f * f * (3.0 - 2.0 * f);',
    '  return mix(mix(hash12(i), hash12(i + vec2(1.0, 0.0)), u.x),',
    '             mix(hash12(i + vec2(0.0, 1.0)), hash12(i + vec2(1.0, 1.0)), u.x), u.y);',
    '}',
    'float vnoise3(vec3 p){',
    '  vec3 i = floor(p), f = fract(p);',
    '  vec3 u = f * f * (3.0 - 2.0 * f);',
    '  float n000 = hash13(i),                  n100 = hash13(i + vec3(1.0,0.0,0.0));',
    '  float n010 = hash13(i + vec3(0.0,1.0,0.0)), n110 = hash13(i + vec3(1.0,1.0,0.0));',
    '  float n001 = hash13(i + vec3(0.0,0.0,1.0)), n101 = hash13(i + vec3(1.0,0.0,1.0));',
    '  float n011 = hash13(i + vec3(0.0,1.0,1.0)), n111 = hash13(i + vec3(1.0,1.0,1.0));',
    '  return mix(mix(mix(n000, n100, u.x), mix(n010, n110, u.x), u.y),',
    '             mix(mix(n001, n101, u.x), mix(n011, n111, u.x), u.y), u.z);',
    '}',
    '',
    'float fbm2(vec2 p){',
    '  float a = 0.5, s = 0.0;',
    '  mat2 m = mat2(1.62, 1.2, -1.2, 1.62);',
    '  for (int i = 0; i < 5; i++){ s += a * vnoise2(p); p = m * p; a *= 0.5; }',
    '  return s;',
    '}',
    'float fbm3(vec3 p){',
    '  float a = 0.5, s = 0.0;',
    '  for (int i = 0; i < 4; i++){ s += a * vnoise3(p); p *= 2.03; a *= 0.5; }',
    '  return s;',
    '}',
    'float ridged3(vec3 p){',
    '  float a = 0.5, s = 0.0;',
    '  for (int i = 0; i < 4; i++){',
    '    float n = 1.0 - abs(vnoise3(p) * 2.0 - 1.0);',
    '    s += a * n * n; p *= 2.07; a *= 0.5;',
    '  }',
    '  return s;',
    '}',
    '',
    '// ---- cheap divergence-free-ish flow field ----------------------------',
    'vec3 flow3(vec3 p, float t){',
    '  float n1 = fbm3(p * 0.55 + vec3(0.0, t * 0.12, 0.0));',
    '  float n2 = fbm3(p * 0.55 + vec3(5.2, 1.3 - t * 0.10, 2.7));',
    '  float n3 = fbm3(p * 0.55 + vec3(-3.1, 2.4, t * 0.09 + 8.0));',
    '  return normalize(vec3(n1 - 0.5, n2 - 0.5, n3 - 0.5) * 2.6 + 0.0001);',
    '}',
    '',
    '// ---- colour -----------------------------------------------------------',
    'vec3 pal(float t, vec3 a, vec3 b, vec3 c, vec3 d){',
    '  return a + b * cos(TAU * (c * t + d));',
    '}',
    'vec3 spectrum(float t){',
    '  return pal(t, vec3(0.52, 0.48, 0.55), vec3(0.45, 0.42, 0.48), vec3(1.0, 0.98, 0.92), vec3(0.0, 0.22, 0.55));',
    '}',
    'vec3 aces(vec3 x){',
    '  return clamp((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14), 0.0, 1.0);',
    '}',
    'vec3 gamma(vec3 c){ return pow(max(c, 0.0), vec3(1.0 / 2.2)); }',
    'float luma(vec3 c){ return dot(c, vec3(0.2126, 0.7152, 0.0722)); }',
    '',
    '// ---- sdf kit ----------------------------------------------------------',
    'float sdSphere(vec3 p, float r){ return length(p) - r; }',
    'float sdTorus(vec3 p, vec2 t){ vec2 q = vec2(length(p.xz) - t.x, p.y); return length(q) - t.y; }',
    'float sdBox(vec3 p, vec3 b){ vec3 q = abs(p) - b; return length(max(q, 0.0)) + min(max(q.x, max(q.y, q.z)), 0.0); }',
    'float smin(float a, float b, float k){',
    '  float h = clamp(0.5 + 0.5 * (b - a) / k, 0.0, 1.0);',
    '  return mix(b, a, h) - k * h * (1.0 - h);',
    '}',
    '',
    '// ---- camera -----------------------------------------------------------',
    'mat3 lookAt(vec3 eye, vec3 at, vec3 up){',
    '  vec3 f = normalize(at - eye);',
    '  vec3 r = normalize(cross(f, up));',
    '  vec3 u = cross(r, f);',
    '  return mat3(r, u, f);',
    '}',
    '',
    '// ---- screen helpers ---------------------------------------------------',
    '// centred, aspect-corrected coordinates: y spans -0.5 .. 0.5',
    'vec2 screenUV(){ return (gl_FragCoord.xy - 0.5 * uRes) / uRes.y; }',
    'vec2 uvFrom(vec2 frag){ return (frag - 0.5 * uRes) / uRes.y; }',
    '',
    '// ---- starfield ---------------------------------------------------------',
    'float starLayer(vec2 uv, float density, float sharp, float seed){',
    '  vec2 g = uv * density;',
    '  vec2 id = floor(g);',
    '  vec2 f = fract(g) - 0.5;',
    '  vec2 o = hash22(id + seed) - 0.5;',
    '  float d = length(f - o * 0.72);',
    '  float b = hash12(id * 1.37 + seed * 7.1);',
    '  return pow(max(0.0, 1.0 - d * 2.0), sharp) * step(0.62, b) * (0.35 + b);',
    '}',
    '',
    '// ---- film finish: vignette, tonemap, gamma, grain ----------------------',
    'vec3 finish(vec3 c, vec2 uv, float vig){',
    '  float d = length(uv);',
    '  c *= 1.0 - vig * smoothstep(0.30, 1.10, d);',
    '  c = aces(c * 1.06);',
    '  c = gamma(c);',
    '  float g = hash12(gl_FragCoord.xy + fract(uTime) * 91.7) - 0.5;',
    '  c += g * 0.016;',
    '  return c;',
    '}',
    ''
  ].join('\n');

  w.GLSL = { VERT: VERT, PRELUDE: PRELUDE };
})(window);
